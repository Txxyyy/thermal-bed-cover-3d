import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {checkZones} from './zone-checks.mjs';
import {checkThermalRoute} from './check-thermal-route.mjs';
import {checkControllerPlacement} from './check-controller-placement.mjs';
import {checkCoverGeometry} from './check-cover-geometry.mjs';
const baseURL=process.env.THERMAL_TEST_URL||'http://127.0.0.1:5173';
fs.mkdirSync('output/qa',{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
const checks=[],errors=[];
const check=(label,condition)=>{assert.ok(condition,label);checks.push(label);};
try {
 checkCoverGeometry(check);
 checkThermalRoute(check);
 const page=await browser.newPage({viewport:{width:1500,height:1000}});
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 page.on('response',response=>{if(response.status()>=400)errors.push(`${response.status()} ${response.url()}`);});
 await page.goto(baseURL);await page.waitForFunction(()=>window.__thermalStudio?.snapshot().ready);
 const snapshot=()=>page.evaluate(()=>window.__thermalStudio.snapshot());
 await page.waitForTimeout(250);
 let initial=await snapshot();check('WebGL renders the source CAD and model',initial.render.triangles>12000&&initial.cadMeshes===42);
 checkControllerPlacement(initial,check);
 await checkZones(page,check,{output:'output/qa'});
 await page.locator('#cmf').selectOption('A');check('ID material A selectable',(await snapshot()).cmf==='A');await page.locator('#cmf').selectOption('B');
 for(const [view,file] of [['detail','fabric'],['hub','controller'],['overview','overview']]){
   await page.locator(`button[data-camera=${view}]`).click();await page.waitForTimeout(1600);check(`Camera ${view}`, (await snapshot()).camera===view);await page.screenshot({path:`output/qa/${file}.png`});
 }
 const before=await snapshot();await page.locator('#rotate').check();await page.waitForTimeout(300);
 check('Auto rotation moves the camera',JSON.stringify(before.cameraPosition)!==JSON.stringify((await snapshot()).cameraPosition));await page.locator('#reset').click();check('Reset disables rotation',!await page.locator('#rotate').isChecked());
 const box=await page.locator('canvas').boundingBox();await page.mouse.move(box.x+box.width*.5,box.y+box.height*.5);await page.mouse.down();await page.mouse.move(box.x+box.width*.5+100,box.y+box.height*.5+20,{steps:10});await page.mouse.up();
 check('Pointer orbit changes camera',JSON.stringify(before.cameraPosition)!==JSON.stringify((await snapshot()).cameraPosition));await page.locator('#reset').click();
 for(const width of [390,768]){
   await page.setViewportSize({width,height:844});await page.waitForTimeout(1600);
   check(`No horizontal overflow at ${width}px`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   check(`Controls remain within viewport at ${width}px`,await page.locator('.panel').evaluate(el=>el.getBoundingClientRect().right<=innerWidth));
   await page.screenshot({path:`output/qa/${width===390?'mobile':'tablet'}.png`,fullPage:true});
 }
 check('No page, console or HTTP errors',errors.length===0);
 fs.mkdirSync('output/qa-theme',{recursive:true});
 const themePage=await browser.newPage({viewport:{width:1440,height:1000}}),themeErrors=[];
 themePage.on('pageerror',error=>themeErrors.push(error.message));
 themePage.on('console',message=>{if(message.type()==='error')themeErrors.push(message.text());});
 await themePage.goto(`${baseURL}/theme-preview.html`);
 await themePage.waitForFunction(()=>{const s=document.querySelector('#viewer')?.contentWindow?.__thermalStudio?.snapshot();return s?.ready&&s.zones.left.mode==='cool'&&s.zones.right.mode==='warm'&&s.glow.strength.every(value=>value>.65);});
 const themeSnapshot=()=>themePage.locator('#viewer').evaluate(el=>el.contentWindow.__thermalStudio.snapshot());
 const light=await themeSnapshot();await themePage.screenshot({path:'output/qa-theme/light.png'});
 check('APP preview uses one 3D canvas and the light theme',light.theme==='light'&&await themePage.locator('iframe').count()===1&&await themePage.locator('#viewer').evaluate(el=>el.contentDocument.querySelectorAll('canvas').length===1));
 await themePage.locator('[data-theme-choice=dark]').click();
 await themePage.waitForFunction(()=>document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot().theme==='dark');
 await themePage.waitForTimeout(350);
 const dark=await themeSnapshot();await themePage.screenshot({path:'output/qa-theme/dark.png'});
 check('Theme change retains session and both zone states',dark.sessionId===light.sessionId&&dark.zones.left.mode===light.zones.left.mode&&dark.zones.right.mode===light.zones.right.mode);
 await themePage.locator('[data-zone=right]').click();await themePage.locator('[data-mode=idle]').click();
 await themePage.waitForFunction(()=>document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot().zones.right.mode==='off');
 check('Preview controls operate on only the selected zone',(await themeSnapshot()).zones.left.mode==='cool');
 await themePage.locator('[data-mode=heating]').click();
 await themePage.waitForFunction(()=>document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot().zones.right.mode==='warm');
 await themePage.setViewportSize({width:390,height:844});
 await themePage.locator('.preview').scrollIntoViewIfNeeded();await themePage.waitForTimeout(1000);
 check('APP theme preview has no horizontal overflow on phone width',await themePage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await themePage.screenshot({path:'output/qa-theme/mobile-dark.png',fullPage:true});
 await themePage.locator('[data-theme-choice=light]').click();
 await themePage.locator('.preview').scrollIntoViewIfNeeded();
 await themePage.waitForFunction(()=>{const s=document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot();return s.theme==='light'&&s.visible;});
 await themePage.waitForTimeout(350);
 check('Theme switch on phone width keeps both active zones',(await themeSnapshot()).zones.left.mode==='cool'&&(await themeSnapshot()).zones.right.mode==='warm');
 await themePage.screenshot({path:'output/qa-theme/mobile-light.png',fullPage:true});
 await themePage.locator('#viewer').evaluate(el=>el.style.display='none');
 await themePage.waitForFunction(()=>!document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot().visible);
 check('Offscreen theme preview stops rendering',!(await themeSnapshot()).visible);
 await themePage.locator('#viewer').evaluate(el=>el.style.display='block');
 await themePage.waitForFunction(()=>document.querySelector('#viewer').contentWindow.__thermalStudio.snapshot().visible);
 check('Visible theme preview resumes rendering',(await themeSnapshot()).visible);
 check('Theme preview reports no page or console errors',themeErrors.length===0);
 await themePage.close();
 const motion=await browser.newPage({reducedMotion:'reduce'});await motion.goto(baseURL);await motion.waitForFunction(()=>window.__thermalStudio?.snapshot().ready);
 check('Reduced motion starts paused',await motion.evaluate(()=>window.__thermalStudio.snapshot().paused));await motion.close();
 const fallback=await browser.newPage();await fallback.route('**/models/controller.glb',route=>route.fulfill({status:404,body:'missing'}));await fallback.goto(baseURL);await fallback.locator('#error').waitFor({state:'visible'});
 check('Missing model shows an error, not a false success',await fallback.evaluate(()=>!window.__thermalStudio.snapshot().ready&&!!window.__thermalStudio.snapshot().error));await fallback.close();
 const manifest=JSON.parse(fs.readFileSync('public/models/controller-manifest.json','utf8'));
 check('CAD source hash matches conversion record',crypto.createHash('sha256').update(fs.readFileSync('references/source/controller-0916.stp')).digest('hex')===manifest.sourceSHA256);
 const report={date:new Date().toISOString(),baseURL,checks:checks.length,passed:checks,errors};fs.writeFileSync('output/qa/checks.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
} finally {await browser.close();}
